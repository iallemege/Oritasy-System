def esc(s):
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")

def main():
    pairs = {}
    # names
    for k,v in NAMES.items():
        if k and v: pairs[k] = v
    # descs by name
    enc_path = os.path.join(ROOT, "enc_rows.json")
    with open(enc_path, "r", encoding="utf-8-sig") as f:
        rows = json.load(f)
    missing_desc = []
    for r in rows:
        name = (r.get("name") or "").strip()
        desc = (r.get("desc") or "").strip()
        short = (r.get("short") or "").strip()
        if name and name in NAMES:
            pairs[name] = NAMES[name]
        if short and short in NAMES:
            pairs[short] = NAMES[short]
        if name and desc and len(desc) > 12 and not desc.startswith("code:"):
            if name in DESCS:
                pairs[desc] = DESCS[name]
            else:
                missing_desc.append(name)
        # also map by name for description field if browser uses name-only lookups elsewhere
    for k,v in UI.items():
        pairs[k] = v

    # Also load ui_keys and apply any leftover via light heuristics? skip unknowns
    lines = ["# Oritasy whole-game ZH dictionary (English<TAB>中文)",
             "# Generated for 0.0.9.50C — menus/keybinds/encyclopedia/HUD",
             "# Lines starting with # ignored. Descriptions may use \\n escapes.",
             "# Expand path: append more EN\\tZH rows; restart or toggle language."]
    for en in sorted(pairs.keys(), key=lambda s: (s.lower(), s)):
        zh = pairs[en]
        if not zh or zh == en: continue
        lines.append("%s\t%s" % (en.replace("\t"," ").replace("\n"," "), esc(zh)))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT)
    print("entries", len(pairs))
    print("missing_desc_names", len(set(missing_desc)))
    for n in sorted(set(missing_desc))[:40]:
        print("  missing:", n)

if __name__ == "__main__":
    main()
